import json
import os
import platform
import sys
from datetime import datetime
from typing import Dict, List

from crisis_simulation.config import CHAPTER_NUMBER, EXPERIMENT_ID, get_all_workloads
from crisis_simulation.engine import CrisisEngine
from crisis_simulation.policies import BaselinePolicy, TreatmentPolicy


def _now_iso() -> str:
    return datetime.utcnow().isoformat() + "Z"


def main() -> None:
    # Determine evidence directory
    evidence_dir = os.environ.get("BOOKMAS_EVIDENCE_DIR", "/evidence")
    os.makedirs(evidence_dir, exist_ok=True)
    evidence_path = os.path.join(evidence_dir, "results.json")

    workloads = get_all_workloads()

    engine = CrisisEngine()

    runs: List[Dict] = []

    for workload in workloads:
        # Baseline run
        baseline_policy = BaselinePolicy(workload_id=workload.workload_id)
        baseline_result = engine.run(workload=workload, policy=baseline_policy)
        runs.append(
            {
                "variant": "baseline",
                "workload_id": workload.workload_id,
                "run_id": f"{workload.workload_id}_baseline_{_now_iso()}",
                "success": True,
                "metrics": {
                    "time_to_decisive_containment_action": float(
                        baseline_result.time_to_decisive_containment_action
                    )
                },
            }
        )

        # Treatment run
        treatment_policy = TreatmentPolicy(workload_id=workload.workload_id)
        treatment_result = engine.run(workload=workload, policy=treatment_policy)
        runs.append(
            {
                "variant": "treatment",
                "workload_id": workload.workload_id,
                "run_id": f"{workload.workload_id}_treatment_{_now_iso()}",
                "success": True,
                "metrics": {
                    "time_to_decisive_containment_action": float(
                        treatment_result.time_to_decisive_containment_action
                    )
                },
            }
        )

    evidence: Dict = {
        "chapter": CHAPTER_NUMBER,
        "experiment_id": EXPERIMENT_ID,
        "environment": {
            "os": platform.platform(),
            "python": sys.version.split()[0],
        },
        "runs": runs,
        "notes": (
            "This evidence file was generated by an offline deterministic "
            "simulation comparing baseline vs AI-specific crisis policies. "
            "Metrics represent synthetic time-to-containment values in minutes."
        ),
    }

    with open(evidence_path, "w", encoding="utf-8") as f:
        json.dump(evidence, f, indent=2, sort_keys=False)


if __name__ == "__main__":
    main()
