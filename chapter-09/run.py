import json
import os
import platform
from datetime import datetime

from experiment.workloads import run_wl1_normal_operations, run_wl3_abrupt_model_corruption


CHAPTER_NUMBER = 9
EXPERIMENT_ID = "exp-09-operational-resilience-ai-ewd-response"


def get_evidence_path() -> str:
    base = os.environ.get("BOOKMAS_EVIDENCE_DIR", "/evidence")
    return os.path.join(base, "results.json")


def ensure_evidence_dir(path: str) -> None:
    directory = os.path.dirname(path)
    if directory and not os.path.exists(directory):
        os.makedirs(directory, exist_ok=True)


def collect_environment_metadata() -> dict:
    return {
        "os": platform.platform(),
        "python": platform.python_version(),
    }


def main() -> None:
    runs = []

    # WL1_normal_operations
    wl1_baseline = run_wl1_normal_operations(variant="baseline")
    wl1_treatment = run_wl1_normal_operations(variant="treatment")
    runs.extend([wl1_baseline, wl1_treatment])

    # WL3_abrupt_model_corruption
    wl3_baseline = run_wl3_abrupt_model_corruption(variant="baseline")
    wl3_treatment = run_wl3_abrupt_model_corruption(variant="treatment")
    runs.extend([wl3_baseline, wl3_treatment])

    evidence = {
        "chapter": CHAPTER_NUMBER,
        "experiment_id": EXPERIMENT_ID,
        "environment": collect_environment_metadata(),
        "runs": runs,
        "notes": (
            "This evidence was generated by a deterministic, offline-friendly "
            "simulation of baseline vs. treatment monitoring for an AI-driven "
            "credit approval process. Metrics are synthetic but directly "
            "computed from the code paths executed in this sandbox."
        ),
        "generated_at": datetime.utcnow().isoformat() + "Z",
    }

    evidence_path = get_evidence_path()
    ensure_evidence_dir(evidence_path)
    with open(evidence_path, "w", encoding="utf-8") as f:
        json.dump(evidence, f, indent=2, sort_keys=True)


if __name__ == "__main__":
    main()
